from django.contrib import admin
from django.conf import settings
from django.urls import path, re_path
from django.contrib.auth import views as auth_views
from django.views.static import serve
from bibliory import views

urlpatterns = [
    path('admin/', admin.site.urls),
    path('', views.home, name='home'),
    path('register/', views.register, name='register'),
    path('login/', views.login_view, name='login'),
    path('logout/', auth_views.LogoutView.as_view(), name='logout'),
    path('books/<int:pk>/read/', views.read_book, name='read_book'),
]

# This simple media route also works on Render. For larger production sites,
# serve uploads from object storage or a persistent media volume instead.
urlpatterns += [
    re_path(r'^media/(?P<path>.*)$', serve, {'document_root': settings.MEDIA_ROOT}),
]
